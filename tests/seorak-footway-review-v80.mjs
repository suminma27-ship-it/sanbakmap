// v80: topological evidence alone does not promote five held OSM footways to hiking routes.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
const root=new URL('../',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');
const review=JSON.parse(read('audits/seorak-v80-five-footways.geojson'));
const held=JSON.parse(read('audits/seorak-v79-held-candidates.json'));
const v78source=read('seorak-v78-extra.js');
const payload=v78source.match(/SANBAK_SEORAK_V78_B64='([^']+)'/)?.[1];
assert(payload,'v78 source paths required for contact verification');
const v78=JSON.parse(gunzipSync(Buffer.from(payload,'base64')).toString('utf8'));
assert.equal(review.type,'FeatureCollection');
assert.equal(review.data_version,80);
assert.equal(review.display_in_map,false);
assert.equal(review.route_allowed,false);
assert.equal(review.field_verified,false);
assert.equal(review.displayed_map_lines_unchanged,713);
assert.equal(review.reference_gpx_files_checked,6748);
assert.equal(review.reference_gpx_intersections_with_review_area,0);
assert.equal(review.features.length,5);
const known=new Set(held.original_way_ids_by_class.footway_unspecified.map(String));
const ids=new Set(),neighbors=new Set();let metres=0,loops=0;
const hav=(a,b)=>{
 const dr=Math.PI/180,dy=(b[1]-a[1])*dr,dx=(b[0]-a[0])*dr;
 const m=Math.sin(dy/2)**2+Math.cos(a[1]*dr)*Math.cos(b[1]*dr)*Math.sin(dx/2)**2;
 return 12742000*Math.asin(Math.min(1,Math.sqrt(m)));
};
for(const f of review.features){
 const x=f.properties,coords=f.geometry.coordinates;
 assert.equal(f.type,'Feature');
 assert.equal(f.geometry.type,'LineString');
 assert.equal(x.highway,'footway');
 assert.equal(x.field_verified,false);
 assert.equal(x.routing_allowed,false);
 assert(known.has(x.osm_id),'v80 candidate was not held in v79: '+x.osm_id);
 assert(!ids.has(x.osm_id),'duplicate candidate');
 ids.add(x.osm_id);
 assert(coords.length>=2&&coords.every(p=>p.length===2&&p.every(Number.isFinite)));
 const n=v78.paths.find(z=>String(z.i)===x.direct_displayed_neighbor);
 assert(n&&n.h==='footway','v80 junction must connect to v78 displayed footway');
 neighbors.add(x.direct_displayed_neighbor);
 const key=JSON.stringify(x.exact_shared_source_vertex);
 assert(coords.some(pt=>JSON.stringify(pt)===key),'review candidate lacks source junction');
 assert(n.p.some(pt=>JSON.stringify(pt)===key),'v78 neighbor lacks exact source junction');
 const loop=JSON.stringify(coords[0])===JSON.stringify(coords.at(-1));
 assert.equal(x.closed_loop,loop);
 if(loop)loops++;
 let d=0;for(let j=1;j<coords.length;j++)d+=hav(coords[j-1],coords[j]);
 assert(Math.abs(d-x.length_m)<0.2,'length mismatch '+x.osm_id);
 metres+=d;
}
assert.deepEqual([...ids].sort(),['485958084','485958093','485958097','485958100','485958102'].sort());
assert.equal(neighbors.size,3);
assert.equal(loops,1);
assert(metres>413&&metres<416,'unexpected total length '+metres);
const html=read('national-parks-trails.html');
assert(!html.includes('seorak-v80-extra.js'),'no v80 map lines');
assert(!html.includes('window.SanbakNationalRoutes.shortest'),'no new routing');
assert(read('README.md').includes('**현재 버전: v80**'));
console.log('PASS v80: five held OSM footways '+metres.toFixed(1)+'m, 3 exact v78 neighbors, 1 loop, no routing');
