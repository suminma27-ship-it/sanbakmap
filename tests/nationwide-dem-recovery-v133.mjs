assert.equal(x.originalGraphChanged,false);
assert.equal(x.sourceDEMChanged,false);
assert.equal(x.publicRoutingChanged,false);
assert.equal(x.createdNewUIFeatures,false);
assert.equal(x.physicalPassageVerified,false);
