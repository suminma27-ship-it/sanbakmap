// v96: stable waypoint ordering, especially moving the last of 4 to the front.
// These are independent POI labels, never validated route vertices or travel paths.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const sandbox={};
new Function('window',read('seorak-v95-pois.js'))(sandbox);
new Function('window',read('seorak-v96-plan.js'))(sandbox);
const plan=sandbox.SanbakPOIPlanV96;
assert.equal(plan.version,96);
const ids=plan.catalogIds(sandbox.SANBAK_SEORAK_V95_POIS);
assert.equal(ids.length,4);
assert.equal(new Set(ids).size,4);
assert.deepEqual(plan.catalogIds({version:95,park:'seorak',render_as_route_vertices:true}),[]);
let state=[];
for(const id of ids)state=plan.add(state,id,ids);
assert.deepEqual(state,ids);
assert.deepEqual(plan.add(state,ids[3],ids),ids,'Duplicates must never be added');
assert.deepEqual(plan.add(state,'unknown-venue',ids),ids);
const before=state.slice();
state=plan.move(state,ids[3],-1,ids);
assert.deepEqual(state,[ids[0],ids[1],ids[3],ids[2]]);
assert.deepEqual(before,ids,'Move must not mutate original');
state=plan.move(state,ids[3],-1,ids);
assert.deepEqual(state,[ids[0],ids[3],ids[1],ids[2]]);
state=plan.move(state,ids[3],-1,ids);
assert.deepEqual(state,[ids[3],ids[0],ids[1],ids[2]]);
assert.equal(state.length,4,'Last-to-first regression may not delete earlier waypoints');
assert.equal(new Set(state).size,4);
assert.deepEqual(plan.move(state,ids[3],-1,ids),state,'Out of bounds move is no-op');
assert.deepEqual(plan.move(state,ids[3],100,ids),state,'Jump greater than 1 must be rejected');
assert.deepEqual(plan.insertAt(ids,ids[3],0,ids),[ids[3],ids[0],ids[1],ids[2]]);
assert.deepEqual(plan.insertAt(ids,ids[3],3,ids),ids);
assert.deepEqual(plan.remove(state,ids[1],ids),[ids[3],ids[0],ids[2]]);
assert.deepEqual(plan.normalize([ids[0],ids[0],ids[1],'junk',null,ids[2]],ids),ids.slice(0,3));
const encoded=plan.serialize(state,ids),saved=JSON.parse(encoded);
assert.equal(saved.routing_allowed,false);
assert.deepEqual(plan.deserialize(encoded,ids),state);
assert.deepEqual(plan.deserialize('{garbled',ids),[]);
assert.deepEqual(plan.deserialize(JSON.stringify({version:96,park:'seorak',poi_ids:ids,routing_allowed:true}),ids),[]);
assert.deepEqual(plan.deserialize(JSON.stringify({version:95,park:'seorak',poi_ids:ids,routing_allowed:false}),ids),[]);
const summary=plan.summary(state,ids);
assert.equal(summary.kind,'waypoint_order_only');
assert.deepEqual(summary.waypoints,state);
assert.equal(summary.routing_allowed,false);
assert.equal(summary.physical_track_created,false);
assert.equal(summary.distance_km,null);
assert.equal(summary.ascent_m,null);
assert.equal(summary.descent_m,null);
const html=read('national-parks-trails.html');
assert(html.includes('<script src="./seorak-v96-plan.js"></script>'));
assert(html.includes('id="poiPlanPanel"'));
assert(html.includes('id="poiPlanList"'));
assert(html.includes('id="poiPlanPicker"'));
assert(html.includes('id="poiPlanClear"'));
assert(html.includes('function addPlannedPOI(id)'));
assert(html.includes('function showPlanUI()'));
assert(html.includes('poiPlanEngine.move(planIDs,id,action===\'up\'?-1:1,allowedPOIs)'));
assert(html.includes('poiPlanEngine.remove(planIDs,id,allowedPOIs)'));
assert(html.includes('localStorage.setItem(planKey,poiPlanEngine.serialize(planIDs,allowedPOIs))'));
assert(html.includes('renderNamedPOIs()'));
assert(!html.includes('window.SanbakNationalRoutes.shortest'));
assert(!html.includes('seorak-v94-source-contact-anchors.geojson'));
assert(html.includes('excludedSeorakInsideTrailIndices=new Set([89,436,437])'));
assert(html.includes("record.segments.trail.filter((_,i)=>!excludedSeorakInsideTrailIndices.has(i))"));
const b64=html.match(/window\.SANBAK_NP_OSM_B64="([^"]+)"/)?.[1];
assert(b64);
assert.equal(createHash('sha256').update(b64).digest('hex'),
  JSON.parse(read('audits/seorak-v91-display-way-index.json')).v73_embedded_source_sha256);
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,2);
for(const s of scripts)new Function(s[1]);
const audit=JSON.parse(read('audits/seorak-v96-official-junction-review.json'));
const anchors=JSON.parse(read('audits/seorak-v94-source-contact-anchors.json'));
assert.equal(audit.version,96);
assert.equal(audit.evidence_inventory.exact_source_shared_nodes,anchors.source_contacts);
assert.equal(audit.evidence_inventory.named_public_junctions_matching_exact_original_node_and_official_record,0);
assert.equal(audit.named_junctions_added,0);
assert.equal(audit.tracks_added,0);
assert.equal(audit.generated_connectors,0);
assert.equal(audit.automatic_route_planning_enabled,false);
assert(read('.github/workflows/deploy-pages.yml').includes('seorak-v96-plan.js'));
assert(read('sw.js').includes("'./seorak-v96-plan.js'"));
assert(read('README.md').includes('## v96 주요지점 순서 계획'));
console.log('PASS v96: 4 POIs ordered/saved, 4-to-front without loss, no inferred routes, 0 named official junctions');
