// v83: archive-GPX source alignment is display evidence, NOT current legal access or routability.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');
const audit=JSON.parse(read('audits/seorak-v83-grade1-track-gpx-review.json'));
const oldAudit=JSON.parse(read('audits/seorak-v79-held-candidates.json'));
const source=read('seorak-v83-gpx-tracks.js');
const marker=source.match(/window\.SANBAK_SEORAK_V83_GPX_TRACKS=(\{.*\});/);
assert(marker,'v83 original OSM track geometry module must exist');
const trails=JSON.parse(marker[1]);
assert.equal(trails.version,83);
assert.equal(trails.route_allowed,false);
assert.equal(trails.field_verified,false);
assert.equal(trails.paths.length,4);
assert.equal(audit.candidate_count,129);
assert.equal(audit.source_road_only_components,47);
assert.equal(audit.matched_gpx_roads,4);
assert.equal(audit.remaining_held_candidates,125);
assert.equal(audit.park_map_previous_displayed_lines,699);
assert.equal(audit.park_map_next_displayed_lines,703);
assert.equal(audit.current_field_or_legal_access_verified,false);
assert.equal(audit.added_to_automatic_routing,false);
const all=new Set(oldAudit.original_way_ids_by_class.track_paved_or_grade1);
assert.equal(all.size,129);
assert.equal(audit.all_road_way_ids.length,129);
assert.deepEqual(new Set(audit.all_road_way_ids),all);
const aligned=new Set(audit.shown_way_ids);
assert.equal(aligned.size,4);
assert.equal(audit.remaining_held_way_ids.length,125);
for(const id of audit.remaining_held_way_ids)assert(!aligned.has(id)&&all.has(id),'held ways should remain held');
let totalLength=0;
for(const row of trails.paths){
 assert(aligned.has(row.i),'displayed OSM way must have archived GPX alignment');
 assert.equal(row.h,'track');
 assert.equal(row.field_verified,false);
 assert.equal(row.routing_allowed,false);
 assert.equal(row.source_only,true);
 assert(row.n>=5,'multiple near archived GPS samples required');
 assert(row.covered_span_m/row.length_m>=0.6,'a single GPS crossing cannot promote a road');
 assert(row.p.length>=2&&row.p.every(p=>p.length===2&&p.every(Number.isFinite)));
 assert(row.p.every(p=>p[0]>128.1&&p[0]<128.75&&p[1]>37.9&&p[1]<38.38));
 const auditRow=audit.source_alignment_evidence.find(x=>x.id===row.i);
 assert(auditRow&&auditRow.gpx===row.gpx);
 assert(Math.abs(auditRow.source_length_m-row.length_m)<0.1);
 totalLength+=row.length_m;
}
assert(totalLength>1020&&totalLength<1035);
assert.deepEqual(new Set(trails.paths.map(r=>r.i)),aligned);
const html=read('national-parks-trails.html');
assert(html.includes('국립공원 등산로 원본 · v83'));
assert(html.includes('seorak-v83-gpx-tracks.js'));
assert(html.includes('outerSeorak.features.push(...added83)'));
assert(html.includes("v77.a.filter(r=>!excludedFacilityPathIds.has(r.i))"));
assert(html.includes("v78.paths.filter(r=>r.h==='track')"));
assert(!html.includes('reviewToggle')&&!html.includes('seorak-v80-review'));
assert(!html.includes('window.SanbakNationalRoutes.shortest'));
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,2);
for(const script of scripts)new Function(script[1]);
const workflow=read('.github/workflows/deploy-pages.yml');
const pack=workflow.split('\n').find(line=>line.trimStart().startsWith('cp index.html'));
const required=workflow.split('\n').find(line=>line.includes('for file in index.html'));
assert(pack&&required,'Pages packaging must have for and cp lines');
for(const file of ['seorak-v78-extra.js','seorak-v83-gpx-tracks.js']){
 assert(pack.includes(file),'Pages deployment must copy '+file);
 assert(required.includes(file),'Pages deployment must verify '+file);
 assert(read('sw.js').includes('./'+file),'offline shell should cache '+file);
}
assert(read('README.md').includes('**현재 버전: v83**'));
console.log('PASS v83: 4 GPS-aligned OSM tracks ~1.03km, 125 held, v78+v83 assets deployed, no new routing');
