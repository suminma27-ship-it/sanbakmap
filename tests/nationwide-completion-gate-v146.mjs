import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const j=p=>JSON.parse(readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const x=j('audits/v146-nationwide-completion-gate.json');
const p=j('audits/v145-source-endpoint-priority.json');
const q=j('audits/v140-original-coordinate-quantization-summary.json');
const v144=j('audits/v144-v140-archive-reconciliation.json');
assert.equal(x.scope.mountains,q.originalMountainsPreserved);
assert.equal(x.scope.edges,q.originalEdgesPreserved);
assert.equal(x.scope.nodes,q.originalNodesPreserved);
assert.equal(x.inputs.v140ArchiveSHA256,p.sourceArchiveSHA256);
assert.equal(x.inputs.v140ArchiveSHA256,v144.sourceArchiveSHA256);
assert.equal(x.inputs.sourceSHA256,q.inputSHA256.source);
assert.equal(x.inputs.topologySHA256,q.inputSHA256.topology);
assert.equal(x.inputs.graphSHA256,q.inputSHA256.graph);
assert.equal(x.verified.v145PriorityNodes,p.priorityNodeCount);
assert.equal(x.verified.v145PriorityMountains,p.priorityMountains);
assert.equal(x.verified.v145ProvisionalEdgeIncidences,p.priorityProvisionalEdgeIncidences);
assert.equal(x.verified.v140NearCellPairs,q.nearbyDifferentGraphNodePairsAtMost2cm);
assert.equal(x.verified.v140CrossComponentPairs,q.nearbyDifferentGraphNodePairsAtMost2cmAcrossComponents);
assert.equal(p.thresholds.find(z=>z.spreadAboveMeters===.05).nodes,114);
assert.equal(p.thresholds.find(z=>z.spreadAboveMeters===.05).nodesWithProvisionalEdges,57);
assert.equal(p.thresholds.find(z=>z.spreadAboveMeters===.05).provisionalEdgeIncidences,150);
for(let i=1;i<p.thresholds.length;i++){
 const a=p.thresholds[i-1],b=p.thresholds[i];
 assert(a.spreadAboveMeters<b.spreadAboveMeters);
 assert(a.nodes>=b.nodes);
 assert(a.mountains>=b.mountains);
 assert(a.nodesWithProvisionalEdges>=b.nodesWithProvisionalEdges);
 assert(a.provisionalEdgeIncidences>=b.provisionalEdgeIncidences);
}
assert(x.incomplete.length>0);
assert.equal(x.safeToDeclareComplete,false);
assert.equal(x.authorizedPermanentLinks,0);
assert.equal(x.graphModified,false);
assert.equal(x.demModified,false);
assert.equal(x.uiModified,false);
assert.equal(x.below200mRemoved,0);
console.log('PASS v146: nationwide source provenance, monotone priority thresholds, and incomplete-data safety gate');
