import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=(path)=>JSON.parse(readFileSync(new URL('../'+path,import.meta.url),'utf8'));
const s=read('audits/v134-loop-dem-recovery.json');
const p=read('audits/v133-original-dem-source-recovery.json');
const q=read('audits/v132-dem-gap-repair-summary.json');
assert.equal(s.schema,'sanbak-closed-loop-original-dem-recovery-v134');
assert.equal(s.mountainsPreserved,2902);
assert.equal(s.mountainsPreserved,q.mountainCountPreserved);
assert.equal(s.originalSourceEdgesTargeted,q.greedyTargetOriginalEdges);
assert.equal(s.previousV133Verified,p.originalEdgesVerifiedForRecovery);
assert.equal(s.newlyVerifiedClosedSourceLoops,3);
assert.equal(s.newlyVerifiedClosedSourceLoops+s.previousV133Verified,s.verifiedSourceEdgesTotal);
assert.equal(s.verifiedSourceEdgesTotal+s.unresolvedOriginalSourceEdges,s.originalSourceEdgesTargeted);
assert.equal(s.newDEM90mSamples,29);
assert.equal(s.v132OriginalMissingHeightJunctions,q.missingPriorityLinks);
assert.equal(s.pairedTotal+s.unresolvedJunctions,s.v132OriginalMissingHeightJunctions);
assert.equal(s.pairedTotal,p.newlyPairedJoinElevations+s.newlyPairedJunctions);
assert.equal(s.newlyPairedJunctions,s.newlyPairedDetails.length);
assert.equal(s.stillMissing.originalEdgeIds.length,s.unresolvedOriginalSourceEdges);
assert.equal(s.stillMissing.missingJunctions,s.unresolvedJunctions);
assert.equal(s.recoveredSourceEdges.reduce((sum,r)=>sum+r.sampleCount,0),s.newDEM90mSamples);
assert(s.recoveredSourceEdges.every(r=>r.maxDeviationMeters<.3&&r.hausdorffMeters<.3));
assert(s.rechecked90mFalseAlarm.coarse90mHeightDifferenceMeters>15);
assert(s.rechecked90mFalseAlarm.source3DVertexHeightDifferenceMeters<15);
assert(s.rechecked90mFalseAlarm.source3DSampleAnchorErrorsMeters.every(x=>x<.1));
assert.equal(s.sourceHashes.originalShpZip,p.originSourceZipSHA256);
assert.equal(s.sourceHashes.previousV133Zip,p.v133PatchZipSHA256);
assert.equal(s.newPermanentTrailConnections,0);
assert.equal(s.physicalPassageVerified,false);
assert.equal(s.publicMapChanged,false);
assert.equal(s.originalDEMChanged,false);
assert.equal(s.originalGraphChanged,false);
console.log('PASS v134: 3 exact closed-loop source DEM recoveries, 4 additional gap height checks, 2 still missing; 2902 mountains retained');
