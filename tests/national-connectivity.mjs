import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../national.html',import.meta.url),'utf8');
const script=html.split('<script>')[1]?.split('</script>')[0];
assert(script,'National viewer JavaScript was not found');
new Function(script);
assert(html.includes('id="connectivity"'),'Details panel missing');
assert(html.includes("el('connectivity').ontoggle=render"),'Overlay refresh event missing');
assert(html.includes("displayMode==='preview'?710:650"),'Preview vertical drag scale not fixed');
assert(html.includes("displayMode!=='preview'&&!lines.length"),'Preview mouse-wheel zoom not available');
const start=script.indexOf('function diagnoseConnectivity(');
const end=script.indexOf('\n}',start);
assert(start>=0&&end>start,'Connectivity diagnosis missing');
const diagnose=new Function(script.slice(start,end+2)+'\nreturn diagnoseConnectivity')();
const a=[[127,37],[127.001,37]];
const connected=diagnose([a,[[127.001,37],[127.002,37]]]);
assert.equal(connected.components,1,'Exact shared vertex must connect');
assert.equal(connected.dangling,2,'Degree-1 end count incorrect');
assert.equal(connected.candidateTotal,0);
const close=diagnose([a,[[127.00101,37],[127.002,37]]]);
assert.equal(close.components,2,'Nearby endpoints must stay disconnected');
assert.equal(close.candidateTotal,1,'Near gap should be flagged for review');
assert(close.candidates[0].meters>.5&&close.candidates[0].meters<2);
const crossing=diagnose([[[126.999,37],[127.001,37]],[[127,36.999],[127,37.001]]]);
assert.equal(crossing.components,2,'Visual crossing without a shared vertex must stay disconnected');
const branch=diagnose([a,[[127.001,37],[127.002,37]],[[127.001,37],[127.001,37.001]]]);
assert.equal(branch.components,1);assert.equal(branch.dangling,3);
assert.deepEqual(diagnose([]).candidates,[]);
const sw=readFileSync(new URL('../sw.js',import.meta.url),'utf8');
assert(sw.includes("cache.put(req, fresh)"),'Offline navigation must cache its own page path');
assert(!sw.includes("cache.put('./index.html', fresh)"),'National page may not overwrite home offline cache');
